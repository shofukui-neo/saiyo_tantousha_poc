function scoreSignals(t, groups) {
  let s = 0;
  for (const [re, w] of groups) if (re.test(t)) s += w;
  return s;
}

/**
 * 文字起こし（話し言葉）からコール結果を推定（結果の初期値提案）。
 * 重み付きスコアで各カテゴリを採点し最大を採る。判定不能は '' を返す。
 * @param {string} text
 * @returns {string} RESULT_OPTIONS の value いずれか、または ''
 */
function suggestResult(text) {
  const t = norm(text);
  if (!t) return '';

  // 接続前（専用シグナルが十分強い時のみ。接続後の意思決定シグナルが強ければ後段に譲る）
  const unreach = scoreSignals(t, UNREACH_SIG);
  const reception = scoreSignals(t, RECEPTION_SIG);
  const absent = scoreSignals(t, ABSENT_SIG);

  // 接続後スコア
  const appoCore = APPO_CORE.test(t);
  const appoAssist = APPO_ASSIST.test(t);
  const appoAgree = APPO_AGREE.test(t);
  // core（会う/日時の約束）が無いと日付の言及だけでは強く点けない＝断り時期との誤爆防止。
  let appo = 0;
  if (appoCore) appo += 3;
  if (appoAssist) appo += appoCore ? 2 : 1;
  if (appoAgree && (appoCore || appoAssist)) appo += 1;

  const follow = scoreSignals(t, FOLLOW_SIG);
  const refuse = scoreSignals(t, REFUSE_SIG);
  const post = Math.max(appo, follow, refuse);

  // 接続前は「接続後の明確な意思決定が無い」ときに優先
  if (unreach >= 3 && post < 3) return '不通・番号違い';
  if (reception >= 2 && post < 3) return '受付ブロック';
  if (absent >= 3 && post < 2) return '担当者不在';

  if (post <= 0) {
    // 接続後シグナルが皆無 → 接続前の弱いシグナルでフォロー判断
    if (unreach >= 2) return '不通・番号違い';
    if (reception >= 1) return '受付ブロック';
    if (absent >= 1) return '担当者不在';
    return '';
  }

  // 接続後：最大スコア。同点は アポ > お断り > フォロー の順で確定
  //   （会う約束が最上位アウトカム／断りはパイプライン誠実性のためフォローより優先）
  if (appo >= post) return '担当者接触：アポ獲得';
  if (refuse >= post) return '担当者接触：お断り';
  return '担当者接触：営業フォロー';
}

