// ③ 語彙lift（アポ獲得 vs お断り の語彙差＝トークの決定要因）
// ─────────────────────────────────────────────────────────────
const LEX = [
  'LINE', '母集団', 'つなぎ止め', '歩留', '内定者', '説明会', 'マイナビ', 'リクナビ', 'ナビ',
  '面接', '選考', '日程調整', '管理', 'エクセル', '手作業', '連絡', '返信', '既読',
  '事例', '実績', '料金', '費用', '無料', 'トライアル', '予算', '課題', 'ニーズ',
  '検討', '来期', '見直し', '乗り換え', '不満', '効率', '工数', 'フォロー', '温度感',
  '承諾', '辞退', 'エントリー', '応募', '母数', '接点',
];

// テキスト配列に対する各LEX語の「出現した文書数」
function lexDocCounts(texts) {
  const cnt = {}; LEX.forEach((w) => (cnt[w] = 0));
  for (const raw of texts) {
    const t = norm(raw);
    for (const w of LEX) if (t.includes(w)) cnt[w]++;
  }
  return cnt;
}

/**
 * アポ獲得テキスト群 vs お断りテキスト群 の語彙lift。
 * lift = アポ出現率 ÷ お断り出現率（>1でアポに効く語）。
 * @returns {Array<{word:string, appoRate:number, refuseRate:number, lift:number}>}
 */
function computeLift(appoTexts, refusedTexts) {
  const a = lexDocCounts(appoTexts);
  const r = lexDocCounts(refusedTexts);
  const nA = Math.max(1, appoTexts.length);
  const nR = Math.max(1, refusedTexts.length);
  return LEX.map((w) => {
    const appoRate = a[w] / nA;
    const refuseRate = r[w] / nR;
    const lift = refuseRate > 0 ? appoRate / refuseRate : (appoRate > 0 ? Infinity : 0);
    return { word: w, appoRate, refuseRate, lift };
  }).sort((x, y) => y.lift - x.lift);
}

