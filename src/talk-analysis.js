const RESULT_OPTIONS = [
  { value: '担当者接触：アポ獲得', label: '担当者接触：アポ獲得', group: '接続' },
  { value: '担当者接触：営業フォロー', label: '担当者接触：営業フォロー', group: '接続' },
  { value: '担当者接触：お断り', label: '担当者接触：お断り', group: '接続' },
  { value: '担当者不在', label: '担当者不在', group: '接続前' },
  { value: '受付ブロック', label: '受付ブロック（取次不可）', group: '接続前' },
  { value: '再架電', label: '再架電（コールバック依頼）', group: '接続前' },
  { value: '不通・番号違い', label: '不通・番号違い', group: '接続前' },
];
const RESULT_VALUES = RESULT_OPTIONS.map((o) => o.value);

// コール結果 → 接続ファネル上の位置づけ
function classifyResult(result) {
  const r = String(result || '').trim();
  const reached = r.startsWith('担当者接触：');
  return {
    reached,
    refused: r === '担当者接触：お断り',
    appo: r === '担当者接触：アポ獲得',
    follow: r === '担当者接触：営業フォロー',
  };
}

