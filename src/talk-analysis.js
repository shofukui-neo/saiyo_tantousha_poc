/**
 * トーク要素分類（複数該当可）。マッチ要素と該当箇所のサンプルを返す。
 * @param {string} text 文字起こし/コメント等
 * @returns {{labels:string[], elements:Array<{label:string, sample:string}>}}
 */
function classifyTalk(text) {
  const t = norm(text);
  const elements = [];
  for (const [label, re] of TALK_RULES) {
    const m = t.match(re);
    if (m) {
      const idx = t.indexOf(m[0]);
      const sample = t.slice(Math.max(0, idx - 10), idx + 45).trim();
      elements.push({ label, sample });
    }
  }
  return { labels: elements.map((e) => e.label), elements };
}

