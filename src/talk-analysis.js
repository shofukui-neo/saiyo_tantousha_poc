// 自由記述テキスト → 断り理由カテゴリ（単一）
function classifyComment(text) {
  const t = norm(text);
  for (const [label, re] of REASON_RULES) if (re.test(t)) return label;
  return t ? 'その他（分類外の自由記述）' : '(コメントなし)';
}

/**
 * 断り理由の統合分類。構造化ペンディング理由を優先し、無ければ自由記述で補完。
 * @param {{comment?:string, pending?:string}} rec
 * @returns {string} 断り理由カテゴリ
 */
function classifyRefusal({ comment = '', pending = '' } = {}) {
  const p = String(pending || '').trim();
  if (p && p !== '-' && p !== '5回以上連絡したが不在' && PEND_MAP[p]) return PEND_MAP[p];
  return classifyComment(comment);
}

// ─────────────────────────────────────────────────────────────
// ①' コール結果の自動推定（文字起こしから結果プルダウンの初期値を提案）
//    ※ あくまで“提案”。オペレーターがワンクリックで確定・修正する前提。
// ─────────────────────────────────────────────────────────────
const APPO_SIGNAL = /アポ(獲得|イント)?|日程(調整|確定|を決|が決|押さえ)|日時(を)?(決|確定|設定|押さえ)|面談(設定|確定|の(約束|日程|日時))|訪問(の)?(約束|日程|アポ)|来社(いただ|の(約束|日))|お伺い(する(こと|お約束|日)|します)|打ち合わせ(を)?(設定|確定|する(こと|約束))|次回(の)?(訪問|面談|打ち合わせ|アポ|商談)|オンライン(面談|MTG|商談|打ち合わせ)(を)?(設定|確定)|(月|日|時)(に|から)(訪問|面談|お伺い|打ち合わせ|商談)|承諾(いただ|を得|OK)|前向きに(進め|導入|検討する)/;
const FOLLOW_SIGNAL = /資料(を)?(送|お送り|送付|請求)|追って(ご)?連絡|再度(ご)?連絡|改めて(ご)?(連絡|電話|案内)|後日(改めて|連絡|ご案内)|検討(し(ます|たい)|する|いただ|の余地)|前向き(に検討)?|温度感(は)?(高|良|上)|見込み(あり|高)|継続(フォロー|連絡)|次回連絡/;
const ABSENT_SIGNAL = /不在|席を外|外出(中|され)|会議中|折り返し|かけ直|コールバック|担当(者)?(が)?(いな|不在|席にい)|(本日|今)は(いらっしゃ|おりませ)/;
const RECEPTION_SIGNAL = /受付(で|に)?(ブロック|止め|断ら|取次(が)?(不可|でき))|取次(いただけ|できませ|不可|拒否|NG)|お取次ぎ(でき|いただけ)(ませ|ない)|担当部署(不明|が分から)|受付(で)?(門前払|シャットアウト)/;
const UNREACH_SIGNAL = /不通|話し中|番号(が)?(違|間違|使われて|存在しな)|使われて(いな|おら)|欠番|(電話が)?つながらな|コール(のみ|しっぱなし)|鳴りっぱなし/;

/**
 * 文字起こしからコール結果を推定（結果プルダウンの初期値提案）。
 * 判定不能なら '' を返す（オペレーターが選択）。
 * @param {string} text
 * @returns {string} RESULT_OPTIONS の value いずれか、または ''
 */
function suggestResult(text) {
  const t = norm(text);
  if (!t) return '';
  // 接続前シグナルを優先（接続していないのに接続後の結果を付けない）
  if (UNREACH_SIGNAL.test(t)) return '不通・番号違い';
  if (RECEPTION_SIGNAL.test(t)) return '受付ブロック';
  // 接続後：最も強い前向きシグナル＝アポ獲得
  if (APPO_SIGNAL.test(t)) return '担当者接触：アポ獲得';
  // 断り意思（断り理由が実カテゴリに分類される）＋フォロー気配の有無で分岐
  const refusal = classifyComment(t);
  const realRefusal = refusal && !refusal.startsWith('その他') && !refusal.startsWith('(');
  const followish = FOLLOW_SIGNAL.test(t);
  if (realRefusal && !followish) return '担当者接触：お断り';
  if (followish) return '担当者接触：営業フォロー';
  if (realRefusal) return '担当者接触：お断り';
  if (ABSENT_SIGNAL.test(t)) return '担当者不在';
  return '';
}

