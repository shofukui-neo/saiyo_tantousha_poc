'use strict';
/**
 * boshudan-needs — 「新卒の母集団課題ニーズ」判定の規則エンジン（単一の真実の源）
 * =====================================================================
 * BALESCLOUD の既存リード（過去架電・商談ヒアリング履歴つき）から
 * 「**新卒の母集団形成に課題を抱えている**」リードだけを見分ける純ロジック。
 * 依存なし・ネットワーク/APIキー不要（＝完全ローカル規則ベース）。
 * ドライバは build-boshudan-list.js。talk-analysis.js と同じ流儀で規則を1箇所に集約する。
 *
 * ■ なぜBALESのみか
 *   SFのMOCHICA参照エクスポートは自由記述列を持たない。「母集団が集まらない」
 *   という“生の声”はすべてBALES側の履歴に由来する。（cf. [[kento-jiki-bales-only]]）
 *
 * ■ 判定の骨格（誤爆させないための3層）
 *   1) ニーズ規則（強／中）… 母集団の不足・応募/エントリー不足・特定層が採れない 等
 *   2) 充足規則           … 「母集団は足りている/困っていない/安定」＝ニーズ**なし**
 *   3) 中立ガード         … ヒアリング様式の事実記入（「母集団形成方法：マイナビ」）は
 *                            課題ではないので数えない（これが最大の誤爆源）
 *   さらに「中途の話」ガードで、痛みが中途/アルバイトに帰属する文は落とす（新卒特化）。
 *
 * ■ 強度の意味
 *   強 … 母集団（形成）そのものを課題・悩み・不足と明言／課題欄に母集団形成が挙がる
 *   中 … 応募・エントリー・学生が「集まらない/少ない」等、母集団が薄い実態の言及
 */

// ── 正規化（全角数字→半角・空白畳み込み。talk-analysis と同一の流儀）──
const z2h = (s) => String(s || '').replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xFEE0));
const norm = (s) => z2h(s).replace(/\s+/g, ' ');

// 履歴系の自由記述列（この中を走査する）。列名はBALES 266列構造に準拠。
const FREE_FIELDS = [
  'カスタム情報：顧客の課題感',
  'カスタム情報：顧客の現状',
  'カスタム情報：活動メモ',
  'カスタム情報：活動予定コメント',
  'コメント1：内容',
  'コール結果1：コメント',
  '商談1：引き継ぎメモ',
];
// 表示用の短縮ラベル
const FIELD_LABEL = {
  'カスタム情報：顧客の課題感': '課題感',
  'カスタム情報：顧客の現状': '現状',
  'カスタム情報：活動メモ': '活動メモ',
  'カスタム情報：活動予定コメント': '活動予定',
  'コメント1：内容': 'コメント',
  'コール結果1：コメント': 'コール',
  '商談1：引き継ぎメモ': '商談メモ',
};

// ─────────────────────────────────────────────────────────────
// ① ニーズ規則 [カテゴリ, 強度, 正規表現]
//    ※ 「母集団形成方法/手法」は事実記入なので (?!方法|手法) で必ず除く
// ─────────────────────────────────────────────────────────────
const NEED_RULES = [
  // --- 強：母集団（形成）そのものを課題と明言 ---
  ['母集団形成が課題', '強', /母集団(形成)?[^。\n]{0,4}(課題|悩|苦戦|困っ|困り|不足|足りな|弱い|薄い|厳し|できてい?な|作れ|集まらな|伸びな)/],
  ['母集団形成が課題', '強', /母集団(形成)?(が|は|も)?\s?(全く|ほとんど)?(ない|無い|少な)/],
  ['母集団形成が課題', '強', /(課題|悩み|お悩み|ボトルネック|痛み|困りごと)[^。\n]{0,10}(は|が|＝|=|：|:)?\s?母集団/],
  ['採用課題に母集団形成', '強', /(感じている課題|採用課題|課題感?|課題)[：:]?[^■]{0,70}母集団形成(?!方法|手法)/],
  ['母集団を増やしたい', '強', /母集団(形成)?(を|の)?[^。\n]{0,6}(増やし|増加させ|強化|改善|見直|注力|力を入れ|拡大|広げ|作りた|つくりた)/],
  // --- 中：母集団が薄い実態（応募・エントリー・学生が集まらない）---
  ['応募・エントリー不足', '中', /(応募|エントリー|プレエントリー|母数|接触人数)(数|者)?(が|は|も|の)?[^。\n]{0,8}(集まらな|来な|少な|不足|足りな|伸びな|減っ|減少|厳し|苦戦|悩)/],
  ['応募・エントリー不足', '中', /(集まらな|来ない|少な|不足|足りな|伸びな)[^。\n]{0,10}(応募|エントリー|母数)/],
  ['特定層の学生が採れない', '中', /(理系|文系|男性|女性|専門|地方|県内|地元|優秀|技術|有資格|高専|大卒)[^。\n]{0,4}(学生|人材)(が|は|を|の)?[^。\n]{0,10}(集まらな|来な|少な|いな|確保|欲し|採りた|取りた|厳し|苦戦)/],
  ['学生と出会えない', '中', /学生(と|に|が|を)?[^。\n]{0,8}(出会(う|え|い)[^。\n]{0,6}(機会|場)?[^。\n]{0,4}(少な|な[いく])|集まらな|来な|接点(が)?(な|少))/],
  ['説明会・イベント集客', '中', /(説明会|会社説明会|イベント|合説|合同説明会|インターン(シップ)?|オープンカンパニー)[^。\n]{0,12}(集客[^。\n]{0,6}(課題|苦戦|悩|困|できな|弱)|人が来な|集まらな|参加(者|人数)?(が)?(少な|来な|減)|人数(が)?少な)/],
  ['新卒採用に苦戦', '中', /(新卒|学生|採用)[^。\n]{0,4}(採用)?(が|に|は)[^。\n]{0,6}(苦戦|難しく(な|て)|困って(いる|る|い?ま)|うまくいって?い?な)/],
  ['母集団施策を模索', '中', /(母集団|集客)[^。\n]{0,10}(施策|方法|手法|やり方)[^。\n]{0,8}(探|模索|悩|検討したい|知りた|教え)/],
];

// ─────────────────────────────────────────────────────────────
// ② 充足規則（＝母集団ニーズ「なし」。ニーズ規則より優先して打ち消す）
// ─────────────────────────────────────────────────────────────
const SATISFIED_RULES = [
  /母集団[^。\n]{0,14}(足りて|充足|困って(い?な|おら|ませ)|悩んで(い?な|おら|ませ)|課題(感)?(は)?(特に)?(も)?(な|無)|問題(は)?(な|無)|安定|集まるように|集まって(いる|る|きて)|十分|順調|できて(いる|る)|満た|多い)/,
  /(エントリー|応募)(数|者)?[^。\n]{0,10}(は)?(多い|多く|十分|足りて|困って(い?な|ませ)|問題(は)?な|来て(いる|る))/,
  /母集団(も|は)[^。\n]{0,12}課題感?(も)?(な|無)/,
  /(母集団|エントリー|応募)[^。\n]{0,12}(に(は)?)?(特に)?問題(は)?(な|あり?ませ)/,
  // 「課題感は持っていない/特にない」＝ヒアリング結果としてニーズなし
  /課題感?(を|は)?[^。\n]{0,6}(持って|感じて)(い?な|おら|ませ)/,
  /(特に|それといった|パッと)[^。\n]{0,8}課題感?(は)?(な|無|あり?ませ)/,
  // 4桁級のエントリー数＝母集団は薄くない（数字だけの記載を充足として扱う）
  /(エントリー|応募)(数|者数)?[^。\n]{0,6}[1-9][0-9]{3,}/,
];

// ヒアリング様式「■採用チームとして感じている課題 ・A／B／…／その他」の選択肢テンプレ。
// 7項目中6つ以上が残っている＝**未編集のテンプレ**（＝何も選択されていない）ので課題として数えない。
const TEMPLATE_OPTIONS = ['歩留まり改善', '工数削減', '一元管理', 'LINEの利用', 'コストカット', '母集団形成', 'その他'];
const isUntouchedTemplate = (s) => TEMPLATE_OPTIONS.filter((o) => String(s || '').includes(o)).length >= 6;

// ─────────────────────────────────────────────────────────────
// ③ 中途・非新卒ガード（痛みが中途/アルバイト/パートに帰属する文は新卒ニーズにしない）
// ─────────────────────────────────────────────────────────────
const CHUTO_GUARD = /(中途|キャリア採用|アルバイト|パート|派遣|外国人)(の|は|が|も|採用(は|が|の)?)[^。\n]{0,12}(苦戦|集まらな|少な|課題|困|不足|足りな|厳し)/;
const SHINSOTSU_HINT = /新卒|学生|\d{2}卒|母集団|エントリー|応募|説明会|インターン|ナビ|マイナビ|リクナビ/;
// 自社プロダクト（MOCHICA）側の話＝顧客のニーズではない（例:「MOCHICAも母集団や工数部分強化した」）
// 直近（8文字以内）に自社名がある場合のみ。「モチカは知らないが…今は母集団が課題」を消さない距離に留める。
const PRODUCT_GUARD = /(MOCHICA|モチカ|弊社|当社)(も|は|で|が|に|の)?[^。\n]{0,8}母集団/i;

// 走査窓（マッチ位置の前後をスニペットとして切り出す）
const WIN_BEFORE = 28;
const WIN_AFTER = 46;

function windowAt(text, index, matchLen) {
  const s = Math.max(0, index - WIN_BEFORE);
  const e = Math.min(text.length, index + matchLen + WIN_AFTER);
  return text.slice(s, e).trim();
}

/**
 * 1レコードの「新卒母集団課題ニーズ」を判定する。
 * @param {object} rec BALES 266列のレコード（自由記述列を持つ）
 * @returns {{level:''|'中'|'強', categories:string[], hits:Array<{field:string,label:string,category:string,level:string,snippet:string}>, satisfied:Array<{field:string,label:string,snippet:string}>, evidence:string}}
 */
function detectBoshudanNeeds(rec) {
  const hits = [];
  const satisfied = [];
  const seen = new Set(); // 同一スニペットの重複計上を避ける

  for (const field of FREE_FIELDS) {
    const text = norm(rec[field]);
    if (!text) continue;

    // 充足シグナルの収集（打ち消し判定に使う）
    for (const re of SATISFIED_RULES) {
      const m = text.match(re);
      if (m) {
        satisfied.push({ field, label: FIELD_LABEL[field] || field, snippet: windowAt(text, text.indexOf(m[0]), m[0].length) });
        break;
      }
    }

    for (const [category, level, re] of NEED_RULES) {
      const g = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
      let m;
      while ((m = g.exec(text))) {
        if (m[0].length === 0) { g.lastIndex++; continue; }
        const snippet = windowAt(text, m.index, m[0].length);
        // 未編集テンプレ（選択肢が丸残り）は「母集団形成を選んだ」ことにならない
        if (category === '採用課題に母集団形成' && isUntouchedTemplate(m[0])) continue;
        // 打ち消し：同じ文脈に充足表現があれば課題として数えない
        if (SATISFIED_RULES.some((s) => s.test(snippet))) continue;
        // 中途ガード：痛みが中途等に帰属し、新卒の手がかりが無い文は落とす
        if (CHUTO_GUARD.test(snippet) && !SHINSOTSU_HINT.test(snippet.replace(CHUTO_GUARD, ''))) continue;
        // 自社プロダクトの説明文は顧客ニーズではない
        if (PRODUCT_GUARD.test(snippet)) continue;
        // 中シグナルは新卒文脈（新卒/学生/○卒/母集団/応募/エントリー…）を必須にする
        if (level === '中' && !SHINSOTSU_HINT.test(snippet)) continue;
        const key = category + '|' + snippet;
        if (seen.has(key)) continue;
        seen.add(key);
        hits.push({ field, label: FIELD_LABEL[field] || field, category, level, snippet });
      }
    }
  }

  const hasStrong = hits.some((h) => h.level === '強');
  let level = hasStrong ? '強' : (hits.length ? '中' : '');
  // 中どまり × 充足表現あり ＝ 母集団は足りている可能性が高い → ニーズなし扱い
  if (level === '中' && satisfied.length) level = '';

  const categories = [...new Set(hits.filter((h) => level === '強' ? true : h.level === '中').map((h) => h.category))];
  const evidence = hits
    .slice()
    .sort((a, b) => (a.level === b.level ? 0 : a.level === '強' ? -1 : 1))
    .slice(0, 3)
    .map((h) => `[${h.label}] …${h.snippet}…`)
    .join(' ／ ');

  return { level, categories, hits, satisfied, evidence };
}

module.exports = {
  z2h, norm,
  FREE_FIELDS, FIELD_LABEL,
  NEED_RULES, SATISFIED_RULES, CHUTO_GUARD, PRODUCT_GUARD,
  TEMPLATE_OPTIONS, isUntouchedTemplate,
  detectBoshudanNeeds,
};
