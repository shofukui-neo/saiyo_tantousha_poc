'use strict';
/**
 * 業種ラベルの正規化（公的データの業種 → 採点で使うラベル）
 * =====================================================================
 * 公的データの業種は日本標準産業分類の大分類（「卸売業，小売業」「医療，福祉」など）か、
 * 上場区分の東証33業種（「情報・通信業」「陸運業」など）で来る。
 * mochica-fit.js の INDUSTRY_LIFT と icp-rules.js の IT除外は MOCHICA 側のラベル
 * （「流通・小売・物販」「介護・保育・医療法人等」）を見ているので、ここで寄せる。
 *
 * 寄せ先が決められない分類（製造業・電気機器・サービス業 など）は原文のまま返す。
 * 細分ラベル（流通小売40% vs スーパー11%）を大分類から作ることはしない＝推測で上振れさせない。
 * 原文は必ず「業種(原文)」列に残す。
 */

// [正規表現, 寄せ先ラベル]。上から順に最初に当たったもの。
const RULES = [
  // 情報通信業はIT除外に乗せる（MOCHICAではITは経路を問わず最下位＝構造的除外）
  [/^情報・?通信業?$|情報サービス|ソフトウェア/, 'ソフトウェア・情報通信'],
  [/(医療[，,、・]?福祉|^福祉$|^医療$|社会保険・社会福祉・介護|介護)/, '介護・保育・医療法人等'],
  [/(金融業|保険業|^銀行業$|証券|貸金|金融商品取引)/, '金融・保険'],
  [/^小売業$/, '流通・小売・物販'],
  [/^卸売業$/, '商社'],
  [/^卸売業[，,、・]?小売業$/, '流通・小売・物販'],
  [/(運輸業|郵便業|陸運業|海運業|空運業|物流|倉庫)/, '運輸・交通・物流・倉庫'],
  [/^建設業$/, '建設業'],
  [/^不動産業/, '不動産'],
  [/(電気・ガス・熱供給・水道業|^電気・ガス業$)/, '公共インフラ・エネルギー・環境'],
  [/(宿泊業[，,、・]?飲食サービス業|^飲食)/, '外食・フードサービス'],
];

// 「医療法人、社会福祉法人、健康保険組合等保険者」のように法人種別で括られた分類は、
// 社名で医療・福祉の法人と分かるときだけ寄せる（健康保険組合まで介護扱いにしない）。
const CARE_GROUP_RE = /医療法人、社会福祉法人/;
const CARE_NAME_RE = /(医療法人|社会福祉法人)/;

/**
 * @param {string} raw 業種の原文
 * @param {string} [name] 社名（法人種別で括られた分類の判定にだけ使う）
 * @returns {string} 寄せ先ラベル（寄せられなければ原文）
 */
function mapIndustry(raw, name = '') {
  const s = String(raw || '').normalize('NFKC').replace(/\s+/g, '').trim();
  if (!s) return '';
  if (CARE_GROUP_RE.test(s)) return CARE_NAME_RE.test(String(name)) ? '介護・保育・医療法人等' : String(raw).trim();
  for (const [re, label] of RULES) if (re.test(s)) return label;
  return String(raw).trim();
}

module.exports = { mapIndustry, RULES };
